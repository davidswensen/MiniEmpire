// Regenerates packages/shared/src/golden.ts: final state hashes of fixed
// bot-vs-bot games. Run after any intentional gameplay change:  npm run golden
import { writeFileSync } from 'node:fs';
import { botSetup, runBotGame, type GameMode } from '@mini/shared';

const CASES: Array<{ seed: number; mode: GameMode; turns: number; level: number }> = [
  { seed: 1, mode: '1v1', turns: 2400, level: 3 },
  { seed: 99, mode: '1v1', turns: 1200, level: 1 },
  { seed: 7, mode: '2v2', turns: 1500, level: 2 },
  { seed: 42, mode: 'ffa4', turns: 1000, level: 3 },
];

const rows = CASES.map((c) => {
  const t0 = performance.now();
  const r = runBotGame(botSetup(c.seed, c.mode, c.level), c.turns);
  console.log(`${c.mode} seed=${c.seed} turns=${c.turns} hash=${r.final.toString(16)} (${(performance.now() - t0).toFixed(0)} ms)`);
  return `  { seed: ${c.seed}, mode: '${c.mode}', turns: ${c.turns}, level: ${c.level}, hash: 0x${r.final.toString(16)} },`;
});

writeFileSync(new URL('../packages/shared/src/golden.ts', import.meta.url), `// GENERATED by \`npm run golden\`. Final state hashes of fixed bot-vs-bot games.
// Tests (Node) and determinism.html (browsers) must reproduce these exactly.
import type { GameMode } from './types.ts';

export const GOLDEN: Array<{ seed: number; mode: GameMode; turns: number; level: number; hash: number }> = [
${rows.join('\n')}
];
`);
console.log('wrote packages/shared/src/golden.ts');
