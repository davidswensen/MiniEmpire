// Blocky models: every unit, building and resource is a list of boxes.
// Models face +z. Units stand at y=0. Buildings are centered on their footprint.

export type Anim = 'legL' | 'legR' | 'arm' | 'armL' | 'wheel' | 'flag' | 'throw' | 'horseL' | 'horseR';
export type PartColor = number | 'team' | 'teamDark' | 'teamLight';

export interface Part {
  s: [number, number, number]; // size
  p: [number, number, number]; // center
  c: PartColor;
  a?: Anim;
  pivot?: [number, number, number]; // rotation pivot for animated parts
  r?: [number, number, number]; // static rotation (radians)
  minLevel?: number; // castle level needed to show this part
  maxLevel?: number;
}

export interface Model {
  parts: Part[];
  headTop?: [number, number, number]; // where hats sit
  scale?: number;
}

